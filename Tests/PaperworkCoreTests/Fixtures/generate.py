"""Synthetic R1 corpus, no private/user/competitor content. reportlab + pypdf."""
from pathlib import Path
from io import BytesIO
from reportlab.pdfgen import canvas
from pypdf import PdfReader, PdfWriter
from pypdf.generic import ArrayObject, DictionaryObject, NameObject, NumberObject, TextStringObject
root = Path(__file__).resolve().parent
b = BytesIO()
c = canvas.Canvas(b, pagesize=(400, 500), invariant=1)
for label in ['ALPHA FIRST PAGE', 'BRAVO SECOND PAGE', 'CHARLIE THIRD PAGE']:
    c.setFont('Helvetica', 20)
    c.drawString(40, 430, label)
    c.showPage()
c.save()
(root / 'three-pages.pdf').write_bytes(b.getvalue())
f = BytesIO()
c = canvas.Canvas(f, pagesize=(400, 500), invariant=1)
c.setFont('Helvetica', 16)
c.drawString(40, 450, 'Synthetic form - customer name')
c.acroForm.textfield(name='customer', value='Before', x=40, y=390, width=300, height=32, fontSize=16)
c.showPage(); c.save()
(root / 'form.pdf').write_bytes(f.getvalue())
w = PdfWriter(clone_from=PdfReader(BytesIO(b.getvalue())))
w.encrypt('paperwork-test', owner_password='synthetic-owner', algorithm='AES-256')
with (root / 'encrypted.pdf').open('wb') as out: w.write(out)
w = PdfWriter(clone_from=PdfReader(BytesIO(b.getvalue())))
sig = DictionaryObject({NameObject('/Type'): NameObject('/Annot'), NameObject('/Subtype'): NameObject('/Widget'), NameObject('/FT'): NameObject('/Sig'), NameObject('/T'): TextStringObject('signature'), NameObject('/Rect'): ArrayObject([NumberObject(x) for x in [40, 40, 220, 90]])})
ref=w._add_object(sig)
w.pages[0][NameObject('/Annots')] = ArrayObject([ref])
w._root_object[NameObject('/AcroForm')] = DictionaryObject({NameObject('/Fields'): ArrayObject([ref])})
with (root / 'signature-field.pdf').open('wb') as out: w.write(out)
# Not cryptographically signed. It covers the conservative /ByteRange detection branch.
(root / 'signature-marker.pdf').write_bytes(b.getvalue() + b'\n% synthetic signature detection /ByteRange [0 1 2 3]\n')
print('Created five synthetic inputs; signature fixtures are detection cases, not signed-document verification.')
controls = BytesIO()
c = canvas.Canvas(controls, pagesize=(400, 500), invariant=1)
c.setFont('Helvetica', 12)
c.drawString(30, 470, 'Synthetic form controls')
c.drawString(30, 430, 'Consent')
c.acroForm.checkbox(name='consent', checked=False, x=200, y=420)
c.drawString(30, 385, 'Delivery: Standard / Express')
c.acroForm.radio(name='delivery', value='standard', selected=True, x=230, y=375)
c.acroForm.radio(name='delivery', value='express', selected=False, x=285, y=375)
c.drawString(30, 335, 'Region')
c.acroForm.choice(name='region', options=[('United Kingdom', 'GB'), ('France', 'FR')], value='GB', x=150, y=320, width=210)
c.drawString(30, 270, 'Max length five')
c.acroForm.textfield(name='short', value='12345', maxlen=5, x=150, y=255, width=210)
c.drawString(30, 210, 'Password - blocked')
c.acroForm.textfield(name='secret', value='', fieldFlags='password', x=150, y=195, width=210)
c.drawString(30, 150, 'Read-only - blocked')
c.acroForm.textfield(name='fixed', value='Immutable', fieldFlags='readOnly', x=150, y=135, width=210)
c.showPage(); c.save()
(root / 'controls.pdf').write_bytes(controls.getvalue())
print('Created additional controls fixture: checkbox, shared-field radios, export-value choice, text limits/password/read-only.')
